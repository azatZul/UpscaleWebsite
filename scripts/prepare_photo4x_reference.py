"""Write the Photo 4x warm-up reference from the corrected FP32 graph on CPU.

Run with the scripts/photo4x-requirements.txt environment after
prepare_photo4x_models.py. The browser compares its FP16 GPU warm-up tile with
these coarse block means before trusting the device's output.
"""
import argparse
import base64
import hashlib
import json
import re
import subprocess
from pathlib import Path

import numpy as np
import onnxruntime as ort

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MODEL = ROOT / '.web-model-work/photo4x/models/nomos-realplksr-256-fp32-gpu.onnx'
OUTPUT = ROOT / 'src/tool/photo4x-reference.generated.js'
TILE, SCALE = 256, 4


def js(expression):
    script = f"import * as r from './src/tool/photo4x-reference.js'; process.stdout.write(JSON.stringify({expression}));"
    return json.loads(subprocess.run(['node', '--input-type=module', '-e', script], cwd=ROOT, check=True,
                                     capture_output=True, text=True).stdout)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--model', type=Path, default=DEFAULT_MODEL)
    args = parser.parse_args()
    release = (ROOT / 'src/tool/photo4x-release.js').read_text()
    revision = re.search(r"const sha256 = '([0-9a-f]{64})'", release).group(1)
    grid = js('r.PHOTO4X_REFERENCE_GRID')
    # The JS generator is the single definition of the input.
    data = bytes(js('Array.from(r.photo4xReferenceBytes(%d))' % TILE))
    image = np.frombuffer(data, dtype=np.uint8).reshape(TILE, TILE, 3)
    tensor = (image.astype(np.float32) / 255).transpose(2, 0, 1)[None]
    options = ort.SessionOptions()
    options.graph_optimization_level = ort.GraphOptimizationLevel.ORT_DISABLE_ALL
    session = ort.InferenceSession(str(args.model), options, providers=['CPUExecutionProvider'])
    output = session.run(None, {session.get_inputs()[0].name: tensor})[0][0]
    if not np.isfinite(output).all():
        raise SystemExit('Reference output is not finite')
    # Same quantization as tensorPixels: clamp, scale, round half away from zero.
    pixels = np.floor(np.clip(output, 0, 1).astype(np.float64) * 255 + .5).transpose(1, 2, 0)
    side = TILE * SCALE
    block = side // grid
    means = pixels.reshape(grid, block, grid, block, 3).mean(axis=(1, 3))
    stats = np.floor(means + .5).astype(np.uint8).tobytes()
    model_sha = hashlib.sha256(args.model.read_bytes()).hexdigest()
    OUTPUT.write_text(
        '// Generated by scripts/prepare_photo4x_reference.py. Do not edit.\n'
        f'// Corrected FP32 graph {model_sha} on CPU; deterministic input from photo4x-reference.js.\n'
        'export const PHOTO4X_REFERENCE = Object.freeze({\n'
        f"  revision: '{revision}', grid: {grid},\n"
        f"  stats: '{base64.b64encode(stats).decode()}',\n"
        '});\n')
    print(f'Wrote {OUTPUT.relative_to(ROOT)} for {revision[:16]} ({len(stats)} values)')


if __name__ == '__main__':
    main()
